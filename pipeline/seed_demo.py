"""Seed the database with synthetic traces, so the system can be exercised end to end.

For checking that the parts are wired together — API, database, clustering,
GTFS export, the web map — without riding a kombi first. The traces are
generated by `synthetic.py`, so they follow known corridors and stand still at
known places: whatever comes out the far end can be checked against what went in.

    python seed_demo.py --fake-match     # no OSRM needed
    python cluster.py --replace
    python gtfs.py

Traces are **uploaded over HTTP**, not inserted directly, so this exercises the
real ingest path — the API must be running.

`--fake-match` writes each trace's *cleaned* geometry into `matched_geom` and
marks it `matched`, standing in for the map-matching stage. That is not map
matching and the result is not a road: it is a smoothed GPS track. It exists so
clustering, the export and the map can be exercised before an OSRM dataset has
been prepared (see ../infra/README.md), which is a multi-gigabyte one-off. Once
OSRM is up, `python process.py --all` re-matches these properly.

This is a development tool. Nothing in the pipeline imports it, and seeded rows
are ordinary rows — clear them out with `--replace` on the next clustering run,
or truncate the tables.
"""

from __future__ import annotations

import argparse
import logging
import math
import time

import httpx
from shapely.geometry import LineString

from clean import WGS84, clean_trace, load_trace
from config import get_engine
from match import store_matched_geom
from process import STATUS_MATCHED, set_status
from synthetic import DEFAULT_ORIGIN, synthetic_trace

logger = logging.getLogger(__name__)

#: Three corridors out of central Harare, as waypoints in metres from
#: `synthetic.DEFAULT_ORIGIN`. Directions and rough lengths are plausible for
#: the real network; the exact geometry is not, and is not meant to be.
CORRIDORS: dict[str, tuple[tuple[float, float], ...]] = {
    "south-east": ((0.0, 0.0), (2500.0, -1200.0), (4200.0, -3000.0)),
    "south-west": ((0.0, 0.0), (-2000.0, -1500.0), (-4500.0, -3200.0)),
    "south": ((0.0, 0.0), (500.0, -2500.0), (1200.0, -6000.0)),
}

#: Kombis in traffic, roughly.
SPEED_MPS = 12.0

#: Each trace stops three times, for this long. Comfortably over
#: `stops.MIN_DWELL_S`, so every stop should be detected.
DWELL_S = 30.0

#: How far apart two traces of the same corridor are pulled, in metres. Well
#: inside `cluster.ROUTE_EPS_M` (200) so they cluster into one route, and inside
#: `cluster.STOP_EPS_M` (40) so their dwells cluster into shared stops.
JITTER_M = 8.0


def corridor_length(waypoints: tuple[tuple[float, float], ...]) -> float:
    return sum(math.dist(waypoints[i], waypoints[i + 1]) for i in range(len(waypoints) - 1))


def plan(
    waypoints: tuple[tuple[float, float], ...],
) -> tuple[float, tuple[tuple[float, float], ...]]:
    """Duration and dwell windows for a corridor.

    The vehicle covers 80% of the corridor — a trace that ran exactly to the
    last waypoint would make the ends unrealistically identical across traces —
    and stops three times along the way.
    """
    moving_s = 0.8 * corridor_length(waypoints) / SPEED_MPS
    dwells = tuple((moving_s * fraction, DWELL_S) for fraction in (0.25, 0.5, 0.75))
    return moving_s + len(dwells) * DWELL_S, dwells


def offset(
    waypoints: tuple[tuple[float, float], ...], metres: float
) -> tuple[tuple[float, float], ...]:
    """Shift a whole corridor sideways, so repeat traces are not identical."""
    return tuple((x + metres, y + metres) for x, y in waypoints)


def build_points(seed: int, waypoints: tuple[tuple[float, float], ...]) -> list[dict]:
    """One synthetic trace, as the JSON body `POST /traces` expects."""
    duration_s, dwells = plan(waypoints)
    trace = synthetic_trace(
        duration_s=duration_s,
        speed_mps=SPEED_MPS,
        dwells=dwells,
        noise_sigma_m=4.0,
        seed=seed,
        waypoints=waypoints,
        origin=DEFAULT_ORIGIN,
    )

    wgs84 = trace.noisy.to_crs(WGS84)
    return [
        {
            "lat": float(geometry.y),
            "lon": float(geometry.x),
            "recorded_at": row.recorded_at.isoformat(),
            "accuracy_m": float(row.accuracy_m),
            "speed_mps": float(row.speed_mps),
        }
        for row, geometry in zip(wgs84.itertuples(), wgs84.geometry, strict=True)
    ]


def upload(client: httpx.Client, contributor: str, points: list[dict]) -> int:
    """Upload one trace, waiting out the API's rate limit if it asks us to.

    Ingest is rate-limited per client (see api/app/security.py), and seeding a
    dozen traces back to back is exactly the burst that limit exists to refuse.
    Honouring `Retry-After` rather than raising both keeps the tool working and
    keeps the limit real — the alternative, an exemption for seeding, would mean
    the limit was never exercised by the one client that reliably trips it.
    """
    while True:
        response = client.post("/traces", json={"contributor": contributor, "points": points})

        if response.status_code != httpx.codes.TOO_MANY_REQUESTS:
            response.raise_for_status()
            return int(response.json()["id"])

        delay = float(response.headers.get("retry-after", "60"))
        logger.info("Rate limited by the API; waiting %.0f s before the next upload.", delay)
        time.sleep(delay)


def fake_match(trace_id: int) -> None:
    """Store the cleaned geometry as if it had been matched. See the docstring."""
    engine = get_engine()
    cleaned = clean_trace(load_trace(trace_id, engine=engine))
    line = LineString([(point.x, point.y) for point in cleaned.geometry])
    store_matched_geom(trace_id, line, engine=engine)
    set_status(trace_id, STATUS_MATCHED, engine=engine)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--api", default="http://localhost:8000", help="base URL of the API (no trailing slash)"
    )
    parser.add_argument(
        "--per-route",
        type=int,
        default=4,
        help="traces per corridor (default 4; stops need 3 agreeing traces)",
    )
    parser.add_argument("--contributor", default="demo", help="contributor name to upload as")
    parser.add_argument(
        "--fake-match",
        action="store_true",
        help="store cleaned geometry as matched_geom, so clustering can run without OSRM",
    )
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")

    if args.per_route < 3:
        logger.warning(
            "%d traces per corridor is under cluster.STOP_MIN_SUPPORT (3), "
            "so routes will cluster but no stops will.",
            args.per_route,
        )

    uploaded: list[int] = []
    with httpx.Client(base_url=args.api.rstrip("/"), timeout=60.0) as client:
        for index, (name, waypoints) in enumerate(CORRIDORS.items()):
            for run in range(args.per_route):
                seed = index * 100 + run
                jittered = offset(waypoints, (run - args.per_route / 2) * JITTER_M)
                trace_id = upload(client, args.contributor, build_points(seed, jittered))
                uploaded.append(trace_id)
                logger.info("Uploaded trace %d along the %s corridor.", trace_id, name)

    print(f"Uploaded {len(uploaded)} trace(s) across {len(CORRIDORS)} corridor(s).")

    if args.fake_match:
        for trace_id in uploaded:
            fake_match(trace_id)
        print(f"Marked {len(uploaded)} trace(s) matched using cleaned geometry (no OSRM).")
        print("Next: python cluster.py --replace && python gtfs.py")
    else:
        print("Next: python process.py --full   (needs OSRM)")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
